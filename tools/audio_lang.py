def main():
    for f, k in (('en_us.json', 0), ('fr_fr.json', 1)):
        p = L / f
        d = json.loads(p.read_text(encoding='utf-8'))
        for key, v in T.items():
            d[key] = v[k]
        p.write_text(json.dumps(d, ensure_ascii=False, indent=2), encoding='utf-8')
    print(len(T), 'keys')


if __name__ == '__main__':
    main()
